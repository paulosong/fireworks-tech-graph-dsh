#!/usr/bin/env bash
#
# sync_upstream.sh
# ----------------
# Refresh the vendored upstream skill in skills/fireworks-tech-graph/ from
# yizhiyanhua-ai/fireworks-tech-graph (default branch: main).
#
# This repo wraps that upstream skill for DeepSeek Harness. The upstream is
# MIT-licensed and allow_forking=true, so re-vendoring it here is permitted
# as long as its LICENSE/attribution is preserved (see NOTICE and LICENSE).
#
# Usage:
#   ./sync_upstream.sh
#
# Env overrides:
#   UPSTREAM_REPO    default: yizhiyanhua-ai/fireworks-tech-graph
#   UPSTREAM_BRANCH  default: main
#   SKILL_DIR        default: skills/fireworks-tech-graph
#   BUMP_VERSION     default: 1   (set 0 to skip the patch-version bump)
#
set -euo pipefail

UPSTREAM_REPO="${UPSTREAM_REPO:-yizhiyanhua-ai/fireworks-tech-graph}"
UPSTREAM_BRANCH="${UPSTREAM_BRANCH:-main}"
SKILL_DIR="${SKILL_DIR:-skills/fireworks-tech-graph}"
BUMP_VERSION="${BUMP_VERSION:-1}"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

echo "→ Fetching $UPSTREAM_REPO@$UPSTREAM_BRANCH ..."
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

ARCHIVE="$TMP/up.tar.gz"
curl -fsSL "https://github.com/$UPSTREAM_REPO/archive/refs/heads/$UPSTREAM_BRANCH.tar.gz" -o "$ARCHIVE"
tar -xzf "$ARCHIVE" -C "$TMP"

SRC="$(find "$TMP" -maxdepth 1 -type d -name "${UPSTREAM_REPO##*/}-*")"
if [ -z "$SRC" ]; then
  echo "✗ Could not locate the extracted upstream directory under $TMP" >&2
  exit 1
fi

# Resolve upstream HEAD commit sha for bookkeeping (used by UPSTREAM_COMMIT).
SHA="$(curl -fsSL "https://api.github.com/repos/$UPSTREAM_REPO/commits/$UPSTREAM_BRANCH" \
  | python3 -c 'import sys,json;print(json.load(sys.stdin)["sha"][:7])')"

echo "→ Upstream HEAD: $SHA"
echo "→ Replacing $SKILL_DIR ..."
rm -rf "$SKILL_DIR"
mkdir -p "$(dirname "$SKILL_DIR")"
cp -R "$SRC" "$SKILL_DIR"

# Record tracking metadata.
cat > UPSTREAM_COMMIT <<EOF
# Auto-generated by sync_upstream.sh — do not edit by hand.
UPSTREAM_REPO=$UPSTREAM_REPO
UPSTREAM_BRANCH=$UPSTREAM_BRANCH
UPSTREAM_COMMIT=$SHA
SYNCED_AT=$(date -u +%Y-%m-%dT%H:%M:%SZ)
EOF

# Bump the plugin's patch version so each sync is a distinct, publishable release.
if [ "$BUMP_VERSION" = "1" ]; then
  python3 - <<'PY'
import json
p = "package.json"
d = json.load(open(p, encoding="utf-8"))
v = d.get("version", "1.2.0")
core = v.split("-")[0]
parts = (core.split(".") + ["0", "0", "0"])[:3]
parts[2] = str(int(parts[2]) + 1)
d["version"] = ".".join(parts)
with open(p, "w", encoding="utf-8") as f:
    json.dump(d, f, indent=2, ensure_ascii=False)
    f.write("\n")
print("→ Bumped plugin version to", d["version"])
PY
fi

echo "✓ Done. Review with 'git diff', then commit (CI will open a PR on change)."
